using Meridian.Models.Providers;
using Microsoft.Extensions.AI;
using Xunit;

namespace Meridian.Tests.Models;

/// <summary>
/// A minimal <see cref="IChatClient" /> stub that either returns a fixed reply or throws.
/// </summary>
/// <param name="reply">The text to return, or <see langword="null" /> to throw <see cref="InvalidOperationException" /> instead.</param>
internal sealed class StubChatClient(string? reply) : IChatClient {
    /// <summary>
    /// Gets the call count.
    /// </summary>
    /// <value>The call count.</value>
    public int CallCount { get; private set; }

    /// <summary>
    /// Sends chat messages and returns the response.
    /// </summary>
    /// <param name="messages">The sequence of chat messages to send.</param>
    /// <param name="options">The chat options with which to configure the request.</param>
    /// <param name="cancellationToken">The <see cref="T:System.Threading.CancellationToken" /> to monitor for cancellation requests. The default is <see cref="P:System.Threading.CancellationToken.None" />.</param>
    /// <returns>The response messages generated by the client.</returns>
    /// <exception cref="System.InvalidOperationException">Simulated provider failure.</exception>
    /// <related type="Article" href="https://learn.microsoft.com/dotnet/ai/microsoft-extensions-ai#request-a-chat-response">Request a chat response.</related>
    public Task<ChatResponse> GetResponseAsync(IEnumerable<ChatMessage> messages, ChatOptions? options = null, CancellationToken cancellationToken = default) {
        CallCount++;
        if (reply is null)
            throw new InvalidOperationException("Simulated provider failure.");
        return Task.FromResult(new ChatResponse(new ChatMessage(ChatRole.Assistant, reply)));
    }

    /// <summary>
    /// Sends chat messages and streams the response.
    /// </summary>
    /// <param name="messages">The sequence of chat messages to send.</param>
    /// <param name="options">The chat options with which to configure the request.</param>
    /// <param name="cancellationToken">The <see cref="T:System.Threading.CancellationToken" /> to monitor for cancellation requests. The default is <see cref="P:System.Threading.CancellationToken.None" />.</param>
    /// <returns>A Task&lt;IAsyncEnumerable`1&gt; representing the asynchronous operation.</returns>
    /// <exception cref="System.InvalidOperationException">Simulated provider failure.</exception>
    /// <related type="Article" href="https://learn.microsoft.com/dotnet/ai/microsoft-extensions-ai#request-a-streaming-chat-response">Request a streaming chat response.</related>
    public async IAsyncEnumerable<ChatResponseUpdate> GetStreamingResponseAsync(
        IEnumerable<ChatMessage> messages, ChatOptions? options = null, [System.Runtime.CompilerServices.EnumeratorCancellation] CancellationToken cancellationToken = default) {
        CallCount++;
        if (reply is null)
            throw new InvalidOperationException("Simulated provider failure.");
        yield return new ChatResponseUpdate(ChatRole.Assistant, reply);
        await Task.CompletedTask;
    }

    /// <summary>
    /// Asks the <see cref="T:Microsoft.Extensions.AI.IChatClient" /> for an object of the specified type <paramref name="serviceType" />.
    /// </summary>
    /// <param name="serviceType">The type of object being requested.</param>
    /// <param name="serviceKey">An optional key that can be used to help identify the target service.</param>
    /// <returns>The found object, otherwise <see langword="null" />.</returns>
    /// <remarks>The purpose of this method is to allow for the retrieval of strongly typed services that might be provided by the <see cref="T:Microsoft.Extensions.AI.IChatClient" />,
    /// including itself or any services it might be wrapping. For example, to access the <see cref="T:Microsoft.Extensions.AI.ChatClientMetadata" /> for the instance,
    /// <see cref="M:Microsoft.Extensions.AI.IChatClient.GetService(System.Type,System.Object)" /> may be used to request it.</remarks>
    public object? GetService(Type serviceType, object? serviceKey = null) => null;

    /// <summary>
    /// Performs application-defined tasks associated with freeing, releasing, or resetting unmanaged resources.
    /// </summary>
    public void Dispose() { }
}

/// <summary>
/// Unit tests for <see cref="FallbackChatClient" />.
/// </summary>
public sealed class FallbackChatClientTests {
    /// <summary>
    /// The s messages
    /// </summary>
    private static readonly ChatMessage[] s_messages = [new(ChatRole.User, "hello")];

    /// <summary>
    /// When the first client succeeds, it is used and no other client is called.
    /// </summary>
    [Fact]
    public async Task GetResponseAsync_FirstClientSucceeds_UsesFirstClient() {
        var first = new StubChatClient("from-first");
        var second = new StubChatClient("from-second");
        var client = new FallbackChatClient([(first, "First"), (second, "Second")]);

        var response = await client.GetResponseAsync(s_messages);

        Assert.Equal("from-first", response.Text);
        Assert.Equal(1, first.CallCount);
        Assert.Equal(0, second.CallCount);
    }

    /// <summary>
    /// When the first client throws, the call falls through to the next client in order.
    /// </summary>
    [Fact]
    public async Task GetResponseAsync_FirstClientFails_FallsThroughToSecond() {
        var first = new StubChatClient(null);
        var second = new StubChatClient("from-second");
        var client = new FallbackChatClient([(first, "First"), (second, "Second")]);

        var response = await client.GetResponseAsync(s_messages);

        Assert.Equal("from-second", response.Text);
        Assert.Equal(1, first.CallCount);
        Assert.Equal(1, second.CallCount);
    }

    /// <summary>
    /// When every client fails, the last client's own exception propagates unwrapped (not an AggregateException).
    /// </summary>
    [Fact]
    public async Task GetResponseAsync_AllClientsFail_PropagatesLastClientsException() {
        var client = new FallbackChatClient([(new StubChatClient(null), "First"), (new StubChatClient(null), "Second")]);

        await Assert.ThrowsAsync<InvalidOperationException>(() => client.GetResponseAsync(s_messages));
    }

    /// <summary>
    /// An empty inner client list is rejected at construction time.
    /// </summary>
    [Fact]
    public void Constructor_EmptyInnerList_Throws() {
        Assert.Throws<ArgumentException>(() => new FallbackChatClient([]));
    }
}
